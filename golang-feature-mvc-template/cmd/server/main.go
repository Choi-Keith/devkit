// Command server 是应用入口:加载配置、手工装配依赖
// (configs → infra → feature service/handler → 路由)并启动
// 带优雅退出的 HTTP 服务。不引入容器 / 依赖注入框架。
package main

import (
	"context"
	"flag"

	"github.com/gin-gonic/gin"
	swaggerFiles "github.com/swaggo/files"
	ginSwagger "github.com/swaggo/gin-swagger"
	"go.uber.org/zap"

	"github.com/Choi-Keith/golang-common/auth"
	commoncache "github.com/Choi-Keith/golang-common/cache"
	"github.com/Choi-Keith/golang-common/database"
	"github.com/Choi-Keith/golang-common/health"
	"github.com/Choi-Keith/golang-common/logger"
	"github.com/Choi-Keith/golang-common/middleware"
	"github.com/Choi-Keith/golang-common/server"

	"github.com/Choi-Keith/golang-feature-mvc-template/configs"
	_ "github.com/Choi-Keith/golang-feature-mvc-template/docs" // generated by swag init
	infracache "github.com/Choi-Keith/golang-feature-mvc-template/internal/infra/cache"
	ordermodel "github.com/Choi-Keith/golang-feature-mvc-template/internal/infra/db/order/model"
	orderrepo "github.com/Choi-Keith/golang-feature-mvc-template/internal/infra/db/order/repository"
	usermodel "github.com/Choi-Keith/golang-feature-mvc-template/internal/infra/db/user/model"
	userrepo "github.com/Choi-Keith/golang-feature-mvc-template/internal/infra/db/user/repository"
	"github.com/Choi-Keith/golang-feature-mvc-template/internal/order"
	orderhandler "github.com/Choi-Keith/golang-feature-mvc-template/internal/order/handler"
	orderservice "github.com/Choi-Keith/golang-feature-mvc-template/internal/order/service"
	"github.com/Choi-Keith/golang-feature-mvc-template/internal/user"
	userhandler "github.com/Choi-Keith/golang-feature-mvc-template/internal/user/handler"
	userservice "github.com/Choi-Keith/golang-feature-mvc-template/internal/user/service"
)

// Version 在构建期通过 -ldflags 注入。
var Version = "dev"

// @title						golang-feature-mvc-template API
// @version					1.0
// @description				基于 golang-common 的 feature 纵向切分(feature-MVC)脚手架服务
// @host						localhost:8082
// @BasePath					/api/v1
// @securityDefinitions.apikey	BearerAuth
// @in							header
// @name						Authorization
// @description				输入 "Bearer <accessToken>"(中间有空格)
func main() {
	configPath := flag.String("config", "configs/config.yaml", "path to config file")
	flag.Parse()

	cfg, err := configs.Load(*configPath)
	if err != nil {
		logger.Fatal("load config", zap.Error(err))
	}
	if err := logger.Init(&cfg.Log); err != nil {
		logger.Fatal("init logger", zap.Error(err))
	}

	// ---- 基础设施:数据库 + 缓存 ----
	gormDB, err := database.New(cfg.Database)
	if err != nil {
		logger.Fatal("connect database", zap.Error(err))
	}
	if err := gormDB.AutoMigrate(&usermodel.User{}, &ordermodel.Order{}); err != nil {
		logger.Fatal("auto migrate", zap.Error(err))
	}

	redisCache, err := commoncache.NewRedisCache(cfg.Redis)
	if err != nil {
		logger.Fatal("connect redis", zap.Error(err))
	}

	// ---- 认证:access / refresh 两个 JWT 管理器,仅过期时间不同 ----
	accessJWT := auth.NewJWT(auth.JWTConfig{
		Secret:     cfg.JWT.Secret,
		Expiration: cfg.JWT.AccessExpiration,
		Issuer:     cfg.JWT.Issuer,
	})
	refreshJWT := auth.NewJWT(auth.JWTConfig{
		Secret:     cfg.JWT.Secret,
		Expiration: cfg.JWT.RefreshExpiration,
		Issuer:     cfg.JWT.Issuer,
	})

	// ---- feature 装配:infra 实现 → service → handler ----
	// 接口定义在消费方(service 包),infra 只提供具体实现。
	userSvc := userservice.NewService(userrepo.New(gormDB), infracache.New(redisCache), accessJWT, refreshJWT, cfg.JWT.RefreshExpiration)
	userHandler := userhandler.NewHandler(userSvc)

	orderSvc := orderservice.NewService(orderrepo.New(gormDB), userSvc)
	orderHandler := orderhandler.NewHandler(orderSvc)

	healthHandler := health.NewHealthHandler(Version).
		AddChecker("database", health.NewChecker(database.HealthChecker(gormDB))).
		AddChecker("redis", health.NewChecker(func(ctx context.Context) error {
			return redisCache.Client().Ping(ctx).Err()
		}))

	// ---- 路由 ----
	r := gin.New()
	r.Use(
		middleware.RequestID(),
		middleware.Recovery(),
		middleware.Logging(middleware.LoggingConfig{
			SkipPaths: []string{"/health", "/health/live", "/health/ready"},
		}),
		middleware.CORS(),
	)
	// 限流:进程内存限流仅单实例有效,多实例部署时需换成基于 Redis 的限流。
	// r.Use(middleware.RateLimit(middleware.DefaultRateLimitConfig()))

	healthHandler.RegisterRoutes(r)

	v1 := r.Group("/api/v1")
	user.RegisterRoutes(v1, userHandler)
	order.RegisterRoutes(v1, orderHandler, auth.JWTMiddleware(cfg.JWT.Secret, nil))

	r.GET("/swagger/*any", ginSwagger.WrapHandler(swaggerFiles.Handler))

	// ---- 启动与优雅退出 ----
	srv := server.NewHTTPServer(cfg.Server)
	srv.OnShutdown(func() {
		if err := database.Close(gormDB); err != nil {
			logger.Error("close database", zap.Error(err))
		}
		if err := redisCache.Close(); err != nil {
			logger.Error("close redis", zap.Error(err))
		}
	})

	if err := srv.Run(r); err != nil {
		logger.Fatal("server exited", zap.Error(err))
	}
}
