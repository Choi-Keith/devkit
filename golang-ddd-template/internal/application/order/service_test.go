// fakeRepo is an in-memory test double for order.Repository.
type fakeRepo struct {
	nextID uint64
	byID   map[uint64]*order.Order
}

func newFakeRepo() *fakeRepo {
	return &fakeRepo{nextID: 1, byID: map[uint64]*order.Order{}}
}

func (f *fakeRepo) Save(_ context.Context, o *order.Order) error {
	o.ID = f.nextID // simulate auto-increment
	f.nextID++
	f.byID[o.ID] = o
	return nil
}

func (f *fakeRepo) FindByID(_ context.Context, id uint64) (*order.Order, error) {
	if o, ok := f.byID[id]; ok {
		return o, nil
	}
	return nil, order.ErrNotFound
}

func (f *fakeRepo) List(_ context.Context, page, pageSize int) ([]*order.Order, int64, error) {
	all := make([]*order.Order, 0, len(f.byID))
	for _, o := range f.byID {
		all = append(all, o)
	}
	start := (page - 1) * pageSize
	if start >= len(all) {
		return nil, int64(len(all)), nil
	}
	end := start + pageSize
	if end > len(all) {
		end = len(all)
	}
	return all[start:end], int64(len(all)), nil
}

func (f *fakeRepo) Update(_ context.Context, o *order.Order) error {
	if _, ok := f.byID[o.ID]; !ok {
		return order.ErrNotFound
	}
	f.byID[o.ID] = o
	return nil
}

func TestOrderService_Create(t *testing.T) {
	tests := []struct {
		name    string
		in      CreateInput
		wantErr error
	}{
		{name: "ok", in: CreateInput{UserID: 1, Amount: 199900}},
		{name: "missing user id", in: CreateInput{UserID: 0, Amount: 199900}, wantErr: order.ErrUserIDRequired},
		{name: "invalid amount", in: CreateInput{UserID: 1, Amount: 0}, wantErr: order.ErrInvalidAmount},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			repo := newFakeRepo()
			svc := NewOrderService(repo)

			out, err := svc.Create(context.Background(), tt.in)
			if tt.wantErr != nil {
				if !errors.Is(err, tt.wantErr) {
					t.Fatalf("want error %v, got %v", tt.wantErr, err)
				}
				return
			}
			if err != nil {
				t.Fatalf("unexpected error: %v", err)
			}
			if out.ID == 0 {
				t.Fatal("id must be assigned after save")
			}
			if out.OrderNo == "" {
				t.Fatal("order no must be generated by the service")
			}
			if out.Status != string(order.StatusPending) {
				t.Fatalf("new order must be pending, got %s", out.Status)
			}
		})
	}
}

func TestOrderService_GetByID(t *testing.T) {
	repo := newFakeRepo()
	svc := NewOrderService(repo)

	created, err := svc.Create(context.Background(), CreateInput{UserID: 1, Amount: 199900})
	if err != nil {
		t.Fatalf("setup: %v", err)
	}

	if _, err := svc.GetByID(context.Background(), 9999); !errors.Is(err, order.ErrNotFound) {
		t.Fatalf("want ErrNotFound, got %v", err)
	}

	got, err := svc.GetByID(context.Background(), created.ID)
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	if got.OrderNo != created.OrderNo {
		t.Fatalf("want order no %s, got %s", created.OrderNo, got.OrderNo)
	}
}

func TestOrderService_List(t *testing.T) {
	repo := newFakeRepo()
	svc := NewOrderService(repo)

	for i := 0; i < 3; i++ {
		if _, err := svc.Create(context.Background(), CreateInput{UserID: 1, Amount: 100}); err != nil {
			t.Fatalf("setup: %v", err)
		}
	}

	out, err := svc.List(context.Background(), 1, 2)
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	if out.Total != 3 || len(out.List) != 2 {
		t.Fatalf("want total=3 len=2, got total=%d len=%d", out.Total, len(out.List))
	}

	// Page normalization: invalid values fall back to defaults.
	out, err = svc.List(context.Background(), 0, 0)
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	if out.Page != 1 || out.PageSize != defaultPageSize {
		t.Fatalf("want page=1 pageSize=%d, got page=%d pageSize=%d", defaultPageSize, out.Page, out.PageSize)
	}
}

func TestOrderService_Cancel(t *testing.T) {
	repo := newFakeRepo()
	svc := NewOrderService(repo)

	created, err := svc.Create(context.Background(), CreateInput{UserID: 1, Amount: 199900})
	if err != nil {
		t.Fatalf("setup: %v", err)
	}

	if _, err := svc.Cancel(context.Background(), 9999); !errors.Is(err, order.ErrNotFound) {
		t.Fatalf("want ErrNotFound, got %v", err)
	}

	cancelled, err := svc.Cancel(context.Background(), created.ID)
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	if cancelled.Status != string(order.StatusCancelled) {
		t.Fatalf("want status %s, got %s", order.StatusCancelled, cancelled.Status)
	}

	// Cancelling twice must fail.
	if _, err := svc.Cancel(context.Background(), created.ID); !errors.Is(err, order.ErrNotCancellable) {
		t.Fatalf("want ErrNotCancellable, got %v", err)
	}
}
