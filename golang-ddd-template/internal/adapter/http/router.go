package http

import (
	"github.com/gin-gonic/gin"
	swaggerFiles "github.com/swaggo/files"
	ginSwagger "github.com/swaggo/gin-swagger"

	"github.com/Choi-Keith/golang-common/health"
	"github.com/Choi-Keith/golang-common/middleware"

	_ "github.com/Choi-Keith/golang-ddd-template/docs" // generated by swag init
	orderhttp "github.com/Choi-Keith/golang-ddd-template/internal/adapter/http/order"
	userhttp "github.com/Choi-Keith/golang-ddd-template/internal/adapter/http/user"
)

// NewRouter builds the gin engine with global middleware and all routes.
func NewRouter(userHandler *userhttp.UserHandler, orderHandler *orderhttp.OrderHandler, healthHandler *health.HealthHandler) *gin.Engine {
	r := gin.New()
	r.Use(
		middleware.RequestID(),
		middleware.Recovery(),
		middleware.Logging(middleware.LoggingConfig{}),
		middleware.CORS(),
	)

	healthHandler.RegisterRoutes(r)

	v1 := r.Group("/api/v1")
	users := v1.Group("/users")
	users.POST("", userHandler.Register)
	users.GET("", userHandler.List)
	users.GET("/:id", userHandler.GetByID)
	users.DELETE("/:id", userHandler.Delete)

	orders := v1.Group("/orders")
	orders.POST("", orderHandler.Create)
	orders.GET("", orderHandler.List)
	orders.GET("/:id", orderHandler.GetByID)
	orders.POST("/:id/cancel", orderHandler.Cancel)

	r.GET("/swagger/*any", ginSwagger.WrapHandler(swaggerFiles.Handler))
	return r
}
